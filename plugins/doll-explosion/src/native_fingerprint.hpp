inline auto MatchesBytes(const std::uint8_t* actual, std::size_t actualSize,
        const std::array<std::uint8_t, Size>& expected) noexcept -> bool {
    return actual && actualSize >= Size
        && std::memcmp(actual, expected.data(), Size) == 0;
}

