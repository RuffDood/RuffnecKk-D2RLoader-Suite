// Decode signed rel32 operands, rather than asserting a copied RVA string.
// All RVAs are 32-bit PE-relative values; int64 arithmetic also handles back edges.
template<std::size_t Size>
constexpr auto RelativeTarget(std::uint32_t witnessRva,
        const std::array<std::uint8_t, Size>& bytes,
        std::size_t displacementOffset, std::uint32_t nextOffset) noexcept
        -> std::int64_t {
    if (displacementOffset > Size || Size - displacementOffset < 4) return -1;
    std::uint32_t encoded{};
    for (std::size_t i = 0; i < 4; ++i)
        encoded |= std::uint32_t{bytes[displacementOffset + i]} << (8 * i);
    const auto displacement = encoded < 0x80000000U
        ? std::int64_t{encoded} : std::int64_t{encoded} - 0x100000000LL;
    return std::int64_t{witnessRva} + nextOffset + displacement;
}

