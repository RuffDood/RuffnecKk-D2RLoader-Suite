template<class Read, std::size_t N>
bool Matches(Read& read, std::uintptr_t address, const std::array<std::uint8_t, N>& expected) noexcept {
    std::array<std::uint8_t, N> actual{};
    return read(address, actual.data(), N) && actual == expected;
}
inline bool Add(std::uintptr_t base, std::uintptr_t offset, std::uintptr_t& out) noexcept {
    if (offset > (std::numeric_limits<std::uintptr_t>::max)() - base) return false;
    out = base + offset; return true;
}
template<class Read>
bool RelativeJump(Read& read, std::uintptr_t from, std::uintptr_t& to) noexcept {
    std::array<std::uint8_t, 5> bytes{};
    if (!read(from, bytes.data(), bytes.size()) || bytes[0] != 0xE9) return false;
    std::int32_t displacement{}; std::memcpy(&displacement, bytes.data() + 1, 4);
    std::uintptr_t end{}; if (!Add(from, 5, end)) return false;
    if (displacement >= 0) return Add(end, static_cast<std::uintptr_t>(displacement), to);
    const auto magnitude = static_cast<std::uintptr_t>(-static_cast<std::int64_t>(displacement));
    if (end < magnitude) return false;
    to = end - magnitude; return true;
}
template<class Read>
bool AbsoluteRelay(Read& read, std::uintptr_t from, std::uintptr_t& to) noexcept {
    std::array<std::uint8_t, 14> bytes{};
    constexpr std::array<std::uint8_t, 6> opcode{0xFF, 0x25, 0, 0, 0, 0};
    if (!read(from, bytes.data(), bytes.size()) || std::memcmp(bytes.data(), opcode.data(), 6) != 0) return false;
    std::memcpy(&to, bytes.data() + 6, sizeof(to)); return to != 0;
}
// Accept vanilla, or one exact Move Only hook that forwards this image-widget
// call (return RVA 0x859B48). Its special cases are only 0x2390FC/0x239CC4.
// No hooks are installed here; unknown owners, bodies or trampolines fail closed.
template<class Read>
bool Validate(Read read, std::uintptr_t game, std::uintptr_t owner) noexcept {
    std::uintptr_t entry{}; if (!Add(game, CompanionNative::AssignStringRva, entry)) return false;
    if (Matches(read, entry, CompanionNative::AssignStringBytes)) return true;
    if (!owner || owner > (std::numeric_limits<std::uintptr_t>::max)() - 0x2E5A1) return false;
    std::array<std::uint8_t, 109> tail{};
    if (!read(entry + 5, tail.data(), tail.size())
        || std::memcmp(tail.data(), CompanionNative::AssignStringBytes.data() + 5, tail.size()) != 0) return false;
    std::uintptr_t relay{}, hook{};
    if (!RelativeJump(read, entry, relay) || !AbsoluteRelay(read, relay, hook)
        || hook != owner + HookRva || !Matches(read, hook, HookBytes)
        || !Matches(read, owner + LoadFlagRva, LoadFlagBytes)
        || !Matches(read, owner + FlagAddressRva, FlagAddressBytes)
        || !Matches(read, owner + MemoryOrderRva, MemoryOrderBytes)) return false;
    std::uintptr_t observedGame{}, trampoline{};
    if (!read(owner + GameBaseSlot, &observedGame, sizeof(observedGame)) || observedGame != game
        || !read(owner + OriginalSlot, &trampoline, sizeof(trampoline)) || !trampoline) return false;
    std::array<std::uint8_t, 5> stolen{};
    std::uintptr_t continuation{}, jump{};
    return read(trampoline, stolen.data(), stolen.size())
        && std::memcmp(stolen.data(), CompanionNative::AssignStringBytes.data(), stolen.size()) == 0
        && Add(trampoline, 5, jump) && AbsoluteRelay(read, jump, continuation)
        && continuation == entry + 5;
}
